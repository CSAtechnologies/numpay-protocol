/**
 * Generates spike/expected.json: reference addresses derived on DESKTOP by the
 * exact same @numpay/core code the app runs on device. The on-device spike
 * (runSpike.ts) re-derives everything and must match byte-for-byte — that is
 * the desktop↔device parity gate from NUMPAY_MOBILE_PLAN_2026-07-10.md §2.
 *
 *   node spike/gen-expected.mjs
 */
import { build } from "esbuild";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";

const here = dirname(fileURLToPath(import.meta.url));
const coreSrc = join(here, "..", "..", "packages", "core", "src");

// Standard, publicly-known test mnemonic (hardhat/anvil default). Never holds funds.
const MNEMONIC = "test test test test test test test test test test test junk";

const out = mkdtempSync(join(tmpdir(), "numpay-spike-gen-"));
async function bundle(entry, name) {
  const file = join(out, name + ".mjs");
  await build({ entryPoints: [entry], bundle: true, format: "esm", outfile: file, logLevel: "error" });
  return import(pathToFileURL(file).href);
}

const chains = await bundle(join(coreSrc, "chains", "index.ts"), "chains");
const wallet = await bundle(join(coreSrc, "wallet.ts"), "wallet");

const evm = wallet.importFromMnemonic(MNEMONIC);
const non = await chains.deriveNonEvmAddresses(MNEMONIC);

const expected = {
  _comment: "Generated by spike/gen-expected.mjs from @numpay/core on desktop. The on-device spike must reproduce these exactly.",
  mnemonic: MNEMONIC,
  evm: evm.address,
  bitcoin: non.bitcoin.address,
  solana: non.solana.address,
  sui: non.sui.address,
  tron: non.tron.address,
  xrp: non.xrp.address,
  litecoin: non.litecoin.address,
};

writeFileSync(join(here, "expected.json"), JSON.stringify(expected, null, 2) + "\n");
console.log(expected);
rmSync(out, { recursive: true, force: true });

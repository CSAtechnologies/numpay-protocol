import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const tokenDir = path.join(root, "assets", "token-logos");
const chainDir = path.join(root, "assets", "chain-logos");
const output = path.join(root, "src", "ui", "coinAssets.ts");

const pngs = (dir) => fs.readdirSync(dir)
  .filter((name) => name.toLowerCase().endsWith(".png"))
  .sort((a, b) => a.localeCompare(b));

const tokenEntries = pngs(tokenDir).map((name) =>
  `  ${JSON.stringify(path.basename(name, ".png").toUpperCase())}: require(${JSON.stringify(`../../assets/token-logos/${name}`)}),`
);
const chainEntries = pngs(chainDir).map((name) =>
  `  ${JSON.stringify(path.basename(name, ".png").toLowerCase())}: require(${JSON.stringify(`../../assets/chain-logos/${name}`)}),`
);

const source = `// Generated by scripts/generate-mobile-logo-map.mjs.\n` +
`// Packaged copies of the extension's curated marks; do not edit by hand.\n` +
`import type { ImageSourcePropType } from "react-native";\n\n` +
`const TOKENS: Record<string, ImageSourcePropType> = {\n${tokenEntries.join("\n")}\n};\n\n` +
`const CHAINS: Record<string, ImageSourcePropType> = {\n${chainEntries.join("\n")}\n};\n\n` +
`const key = (value: string) => value.toLowerCase().replace(/[^a-z0-9]/g, "");\n\n` +
`export const tokenAsset = (symbol: string): ImageSourcePropType | undefined => TOKENS[key(symbol).toUpperCase()];\n` +
`export const chainAsset = (chainId: string): ImageSourcePropType | undefined => CHAINS[key(chainId)];\n`;

fs.writeFileSync(output, source);
console.log(`Generated ${path.relative(root, output)} with ${tokenEntries.length} token and ${chainEntries.length} chain marks.`);
